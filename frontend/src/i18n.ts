const DICTS: Record<Lang, Dict> = { en, it, de };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): T {
  return (key, vars) => {
    let text = DICTS[lang][key] ?? en[key] ?? key;
    for (const [name, value] of Object.entries(vars ?? {})) text = text.replace(`{${name}}`, String(value));
    return text;
  };
}

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem("lang");
    if (saved === "en" || saved === "it" || saved === "de") return saved;
  } catch {
    // storage blocked: use the browser's language
  }
  const browser = navigator.language.slice(0, 2);
  return browser === "it" || browser === "de" ? browser : "en";
}

export const I18n = createContext<{ lang: Lang; t: T; setLang: (lang: Lang) => void }>({
  lang: "en",
  t: translator("en"),
  setLang: () => {},
});

export const useI18n = () => useContext(I18n);
